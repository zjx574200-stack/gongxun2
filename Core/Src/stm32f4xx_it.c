/* Capture the original exception frame before a C handler changes the stack.
 * On Cortex-M4, the core registers come first in both basic and FP frames. */
__attribute__((noreturn)) void hardfault_capture(uint32_t *stack, uint32_t exc_return)
{
  uint32_t frame_address;
  uint32_t *frame;

  __disable_irq();
  g_fault.captured = 0U;
  g_fault.boot_stage = g_boot_stage;
  g_fault.cfsr = SCB->CFSR;
  g_fault.hfsr = SCB->HFSR;
  g_fault.bfar = SCB->BFAR;
  g_fault.mmfar = SCB->MMFAR;
  g_fault.shcsr = SCB->SHCSR;
  g_fault.icsr = SCB->ICSR;
  g_fault.exc_return = exc_return;
  g_fault.stack_pointer = (uint32_t)stack;
  g_fault.frame_valid = 0U;

  frame_address = (uint32_t)stack;
  /* Do not dereference an invalid stack or a frame with a stacking error. */
  if (((g_fault.cfsr & 0x1010U) == 0U) &&
      ((frame_address & 3U) == 0U) &&
      (((frame_address >= 0x20000000U) && (frame_address <= 0x2001FFE0U)) ||
       ((frame_address >= 0x10000000U) && (frame_address <= 0x1000FFE0U)))) {
    frame = (uint32_t *)frame_address;
    g_fault.r0 = frame[0];
    g_fault.r1 = frame[1];
    g_fault.r2 = frame[2];
    g_fault.r3 = frame[3];
    g_fault.r12 = frame[4];
    g_fault.lr = frame[5];
    g_fault.pc = frame[6];
    g_fault.xpsr = frame[7];
    g_fault.frame_valid = 1U;
  }
  g_fault.captured = 1U;
  __DSB();
  while (1) {
    __NOP();
  }
}

